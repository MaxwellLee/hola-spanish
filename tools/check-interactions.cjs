const assert=require('node:assert/strict');
const {chromium,devices}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const context=await browser.newContext({...devices['iPhone 13'],defaultBrowserType:undefined});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/#page=17');await page.locator('.content-title').waitFor();
  await page.locator('#pet-toggle').click();assert(await page.locator('#pet-panel').isVisible());
  await page.locator('#pet-input').fill('Hola');await page.locator('#pet-send').click();assert.match(await page.locator('#pet-error').textContent(),/还未连接/);
  await page.screenshot({path:'test-results/iphone-companion.png',fullPage:false});
  await page.locator('#pet-settings').click();await page.locator('#ai-endpoint').fill('https://study.example');await page.locator('#ai-access').fill('test-only-study-password');await page.locator('#save-ai-settings').click();
  await page.route('https://study.example/api/chat',async route=>{assert.equal(route.request().headers()['authorization'],'Bearer test-only-study-password');const data=route.request().postDataJSON();assert.equal(data.context.page,17);await route.fulfill({status:200,contentType:'application/json',headers:{'Access-Control-Allow-Origin':'*'},body:JSON.stringify({reply:'¡Hola! ¿Cómo te llamas?\n你好！你叫什么名字？'})});});
  await page.locator('#pet-send').click();await page.getByText('¡Hola! ¿Cómo te llamas?',{exact:false}).waitFor();
  assert.match(await page.locator('#pet-status').textContent(),/已连接/);
  await page.locator('#pet-close').click();
  await page.locator('.word').filter({hasText:/^Hola$/}).first().click();await page.locator('#retry-translation').click();
  await page.waitForFunction(()=>!document.querySelector('#retry-translation').disabled,{},{timeout:16000});
  const translation=await page.locator('#translation-result').textContent();
  console.log('LIVE_TRANSLATION_RESULT:',translation);
  assert.match(await page.locator('#translation-source').textContent(),/在线翻译/);
  await page.locator('#close-translation').click();
  await page.locator('#menu').click();await page.locator('#nav-words').click();assert(await page.locator('#modal').isVisible());await page.locator('#close-modal').click();
  await page.evaluate(()=>{const n=document.querySelectorAll('.ocr-line')[1];const r=document.createRange();r.selectNodeContents(n);const s=getSelection();s.removeAllRanges();s.addRange(r);});
  await page.locator('#translation').waitFor({state:'visible'});assert((await page.locator('#selected-text').textContent()).length>20);
  assert.deepEqual(errors,[]);
  console.log('Companion: unconfigured state, settings, mock request/response, mobile panel, real online translation, sentence selection all passed.');
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
